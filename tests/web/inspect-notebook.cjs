const { chromium } = require('../../apps/web/node_modules/@playwright/test');
const path = require('node:path');
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(process.env.SATQUERY_TEST_URL || 'http://127.0.0.1:5173', { waitUntil: 'networkidle' });
  await page.screenshot({ path: path.join(__dirname, 'notebook-desktop.png'), fullPage: true });
  const desktopOverflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
  await page.getByRole('button', { name: 'Swipe', exact: true }).click();
  const slider = page.getByRole('slider').first();
  const before = await slider.inputValue(); await slider.focus(); await page.keyboard.press('ArrowRight');
  const after = await slider.inputValue();
  await page.getByRole('button', { name: 'Try an incompatible pair' }).click();
  const rejected = await page.getByRole('region', { name: 'Analysis answer' }).innerText();
  const overlayOnReject = await page.locator('.scene-viewer__overlay').count();
  await page.getByLabel('Load demo example').selectOption('single_image');
  await page.getByRole('button', { name: 'Ask SatQuery', exact: true }).click();
  await page.getByText('A river corridor bordered by farmland and scattered settlements.', { exact: true }).waitFor();
  await page.getByLabel('Load demo example').selectOption('optical_sar');
  await page.getByRole('button', { name: 'Blend', exact: true }).click();
  const fusedText = await page.getByRole('region', { name: 'Scene viewer' }).innerText();
  await page.getByRole('button', { name: 'Ask SatQuery', exact: true }).click();
  await page.getByText('Explore the optical frame, the illustrative SAR stand-in, and a visual blend of the same landscape.', { exact: true }).waitFor();
  const downloadWait = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download JSON', exact: true }).click();
  const download = await downloadWait;
  await download.saveAs(path.join(__dirname, 'downloaded-result.json'));
  await page.getByLabel('Load demo example').selectOption('change');
  await page.getByRole('button', { name: 'Ask SatQuery', exact: true }).click();
  await page.getByText('Possible water expansion along the river’s eastern bank.', { exact: true }).waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: path.join(__dirname, 'notebook-mobile.png'), fullPage: true });
  const mobileOverflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
  await page.getByRole('button', { name: 'Investigations' }).click();
  await page.getByRole('button', { name: 'New investigation', exact: true }).click();
  const disabledWithoutScenes = await page.getByRole('button', { name: 'Ask SatQuery', exact: true }).isDisabled();
  console.log(JSON.stringify({ errors, desktopOverflow, mobileOverflow, slider: { before, after }, rejected, overlayOnReject, fusedText, download: download.suggestedFilename(), disabledWithoutScenes }, null, 2));
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
